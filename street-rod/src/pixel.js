// Rampa de 4 tonos de un color (oscuro, medio, claro y brillo)
function paintRamp(color) {
  return { dk: css(shade(color, -0.38)), md: css(rgbOf(color)), lt: css(shade(color, 0.22)), hi: css(shade(color, 0.55)) };
}
